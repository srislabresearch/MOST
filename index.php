										<article class="box post">
                                            <p style="color:black" align="justify">
											  Mobility shapes our lives. How we get around – be it on foot, by motor vehicle, bicycle, rail, in the air, 
											  or by water vessel – has become an important discussion not only in the field of engineering and computer science, 
											  but also in disciplines such as data science, logistics and operation, health, social sciences, and so on. 
											  New challenges and opportunities arise as the development of connected and autonomous systems meets the demand for 
											  equitable and accessible mobility solutions from diverse communities. <b>The First IEEE International Conference on Mobility: 
											  Operations, Services, and Technologies (MOST)</b> is a new conference that focuses on them.
</p>
<p style="color:black" align="justify">

											IEEE MOST provides a leading international forum that brings together academic researchers and industrial practitioners 
											from diverse fields, with the purpose of exploring the advances and sharing future visions in the field of 
											mobility on land, in the air, and at sea. IEEE MOST 2023 is soliciting high-quality technical papers that focus 
											on innovative and emerging operations, services, and technologies for both indoor and outdoor mobility, including prototypes, 
											infrastructure, tools and software systems, data analytics, logistics operations, novel algorithms and applied artificial intelligence, 
											distributed and connected systems, autonomous vehicles, and so on.
</p>
                                            
